import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const out = resolve(root, ".standalone-build");
mkdirSync(out, { recursive: true });
try {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["standalone/main.tsx"],
    bundle: true,
    platform: "browser",
    format: "esm",
    target: ["chrome110", "safari17"],
    minify: true,
    write: false,
    define: { "process.env.NODE_ENV": '"production"' },
    alias: { "@get-bb/plugin-sdk/app": resolve(root, "standalone/runtime.ts") },
  });
  execFileSync(process.execPath, [
    resolve(root, "node_modules/@tailwindcss/cli/dist/index.mjs"),
    "-i", "standalone/app.css", "-o", resolve(out, "app.css"), "--minify",
  ], { cwd: root, stdio: "inherit" });
  const css = readFileSync(resolve(out, "app.css"), "utf8");
  writeFileSync(resolve(root, "standalone/assets.generated.ts"),
    "// Generated by npm run build:standalone. Do not edit.\n" +
    `export const standaloneJs = ${JSON.stringify(result.outputFiles[0].text)};\n` +
    `export const standaloneCss = ${JSON.stringify(css)};\n`);
  console.log(`Standalone Todo: ${result.outputFiles[0].contents.length} JS bytes, ${css.length} CSS bytes`);
} finally {
  rmSync(out, { recursive: true, force: true });
}
